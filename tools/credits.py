def is_header(s):
    return re.fullmatch(r'[^a-z]+', s) is not None and re.search('[A-Z]', s) is not None


def translate(block):
    out = []
    for line in block.split('\n'):
        s = line.strip()
        lead, trail = line[:len(line) - len(line.lstrip())], line[len(line.rstrip()):]
        if not s:
            out.append(line)
        elif is_header(s):
            out.append(lead + H[s] + trail)  # KeyError: a new heading, add it to H
        elif s in SENT:
            out.append(lead + SENT[s] + trail)
        elif s.endswith(' - Lead'):
            out.append(lead + s[:-len(' - Lead')] + ' - lider' + trail)
        else:
            out.append(line)
    return '\n'.join(out)


